function normalizeCountryKey(name: string): string {
  return name
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
}

const ATLAS_BY_NORMALIZED = new Map<string, string>(
  Object.keys(SPANISH_BY_ATLAS).map((atlasName) => [
    normalizeCountryKey(atlasName),
    atlasName,
  ]),
)

export function resolveAtlasName(catalogName: string): string | null {
  const key = normalizeCountryKey(catalogName)
  return ATLAS_BY_NORMALIZED.get(key) ?? ALIAS_TO_ATLAS[key] ?? null
}

export function catalogNameForAtlas(atlasName: string): string {
  return ATLAS_TO_CATALOG[atlasName] ?? atlasName
}

export function getSpanishCountryName(name: string): string {
  const atlasName = resolveAtlasName(name)
  if (atlasName && SPANISH_BY_ATLAS[atlasName]) {
    return SPANISH_BY_ATLAS[atlasName]
  }
  return SPANISH_BY_CATALOG[name] ?? name
}

function formatGroupedInteger(value: number): string {
  return Math.round(value)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, ".")
}

export function formatCountryTooltip(name: string, titleCount: number): string {
  return `${getSpanishCountryName(name)}: ${formatGroupedInteger(titleCount)} títulos`
}
